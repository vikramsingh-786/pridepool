// Regenerates art.ts from svg/*.svg. Run: npm run gen:art (The Vite original did this with import.meta.glob; webpack has no glob import, so it's a file.)
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const entries = readdirSync(join(here, 'svg'))
  .filter((f) => f.endsWith('.svg'))
  .sort()
  .map((f) => `  '${f.slice(0, -4)}': 'data:image/svg+xml,${encodeURIComponent(readFileSync(join(here, 'svg', f), 'utf8')).replace(/'/g, "\\'")}',`);

writeFileSync(
  join(here, 'art.ts'),
  `/**
 * GENERATED by gen-art.mjs — do not edit. The leaderboard's ${entries.length} Figma SVG layers, bundled into one
 * lazily loaded chunk (see artStore.ts) instead of ${entries.length} separate requests. Each SVG is unchanged
 * (./svg/), just turned into a data: URL, so every <img> and mask still renders its own SVG document.
 */
export const ART: Record<string, string> = {
${entries.join('\n')}
};
`,
);
console.log(`art.ts: ${entries.length} layers`);
